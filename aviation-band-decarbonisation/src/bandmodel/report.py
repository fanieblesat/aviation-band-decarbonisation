def sensitivity(P: Params, df: pd.DataFrame, base: sy.Base) -> dict:
    """One-at-a-time sensitivity of the corrective cost for S2 under (0, 0.82)."""
    def cost(Pv: Params) -> float:
        """LP cost plus uncompensated residuals (cumulative and 2050) priced at the synthetic-SAF backstop."""
        b = sy.build_base(Pv, df) if Pv is not P else base
        s = co.solve(Pv, b, "S2", 0, 0.82)
        backstop = co.mac_table(Pv, b)["alt_ptl"]
        return (s["cost_eur"] + backstop * (s["residual_cum"] + s["residual_2050"])) / 1e9

    ref = cost(P)
    specs = [
        ("Bio-SAF life-cycle reduction", "saf.theta_bio", 0.65, 0.85),
        ("Delivery slots, share of fleet/yr", "corrective.slots_share_of_fleet", 0.01, 0.06),
        ("ATM corrective ceiling", "atm.corrective_max_fraction", 0.55, 0.85),
        ("ATM gross cost, EUR/t CO$_2$", "atm.gross_cost_eur_per_t_co2", 50, 500),
        ("Aircraft price, market/list", "aircraft_classes.market_to_list_ratio", 0.40, 0.60),
        ("Traffic growth, per yr", "demand.flights_growth_per_year", 0.010, 0.022),
        ("Alternative SAF cap, share of fuel", "saf.alt_supply_cap_share", 0.02, 0.10),
        ("Fossil fuel price, EUR/t", "saf.price_fossil_eur_t", 550, 950),
    ]
    rows = []
    for lab, path, lo, hi in specs:
        clo = cost(P.with_overrides({path: lo})); chi = cost(P.with_overrides({path: hi}))
        fmt = (lambda v: f"{100*v:.3g}%") if v_is_share(lo) else (lambda v: f"{v:g}")
        rows.append((lab, clo, chi, fmt(lo), fmt(hi)))
    return {"ref": ref, "rows": rows}


def v_is_share(v: float) -> bool:
    return 0 < v < 1
